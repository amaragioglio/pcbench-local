def detect_language() -> str:
    """Spanish when the OS is in Spanish, English otherwise."""
    candidates = [os.environ.get(var, "") for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG")]
    try:
        candidates.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    try:
        import ctypes  # Windows UI language, e.g. 0x0C0A = es-ES

        candidates.append("es" if (ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF) == 0x0A else "")
    except (AttributeError, OSError):
        pass
    return "es" if any(c.lower().startswith(("es", "spanish")) for c in candidates if c) else "en"


def t(language: str, key: str, **values: object) -> str:
    table = STRINGS.get(language) or STRINGS["en"]
    text = table.get(key) or STRINGS["en"].get(key, key)
    return text.format(**values) if values else text
